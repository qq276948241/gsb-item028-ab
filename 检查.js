#!/usr/bin/env node
"use strict";

// 结露.js 的回归检查。只把原脚本当子进程跑，拿它的真输出逐字比对，不在此重算露点。
// 一条命令跑完：node 检查.js；全过退出码为 0，有一条没过退出码为 1。

var spawnSync = require("child_process").spawnSync;
var path = require("path");

var 脚本路径 = path.join(__dirname, "结露.js");

var 会结露 = "会结露\n";
var 不会结露 = "不会结露\n";
var 倒挂后不会 = "温度倒挂\n" + 不会结露;
var 缺湿度 = "没法结露：缺了湿度\n";
var 别的错 = "没法结露：请给出气温、湿度和物面温度三个整数，湿度要在零到一百\n";

var 用例 = [
  { 名: "气温20、湿度60、物面12正好在露点上，应会结露", 参: ["20", "60", "12"], 退出码: 0, 标准输出: 会结露, 标准错误: "" },
  { 名: "同组物面改成13，应不会结露", 参: ["20", "60", "13"], 退出码: 0, 标准输出: 不会结露, 标准错误: "" },
  { 名: "物面21高于气温，应先温度倒挂再不会结露", 参: ["20", "60", "21"], 退出码: 0, 标准输出: 倒挂后不会, 标准错误: "" },
  { 名: "零下：气温负5、湿度80、物面负9，应会结露", 参: ["-5", "80", "-9"], 退出码: 0, 标准输出: 会结露, 标准错误: "" },
  { 名: "零下：物面负8，应不会结露", 参: ["-5", "80", "-8"], 退出码: 0, 标准输出: 不会结露, 标准错误: "" },
  { 名: "湿度100、物面等于气温20，应会结露，不算倒挂", 参: ["20", "100", "20"], 退出码: 0, 标准输出: 会结露, 标准错误: "" },
  { 名: "只给两段，算缺了湿度", 参: ["20", "12"], 退出码: 2, 标准输出: "", 标准错误: 缺湿度 },
  { 名: "三段里第二段写成缺，算缺了湿度", 参: ["20", "缺", "12"], 退出码: 2, 标准输出: "", 标准错误: 缺湿度 },
  { 名: "一段都没有，报通用错误", 参: [], 退出码: 2, 标准输出: "", 标准错误: 别的错 },
  { 名: "湿度101超出范围，报通用错误", 参: ["20", "101", "12"], 退出码: 2, 标准输出: "", 标准错误: 别的错 },
  { 名: "气温带小数，报通用错误", 参: ["20.5", "60", "12"], 退出码: 2, 标准输出: "", 标准错误: 别的错 },
  { 名: "湿度带正号，报通用错误", 参: ["20", "+60", "12"], 退出码: 2, 标准输出: "", 标准错误: 别的错 },
  { 名: "给了四段，报通用错误", 参: ["20", "60", "12", "9"], 退出码: 2, 标准输出: "", 标准错误: 别的错 }
];

function 跑一次(参) {
  var 结果 = spawnSync(process.execPath, [脚本路径].concat(参), {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"]
  });
  if (结果.error) {
    return { 跑不起来: 结果.error.message };
  }
  return {
    退出码: 结果.status,
    标准输出: 结果.stdout,
    标准错误: 结果.stderr
  };
}

var 失败条数 = 0;

用例.forEach(function (例, 序号) {
  var 首 = 跑一次(例.参);
  var 次 = 跑一次(例.参);
  var 毛病 = [];

  if (首.跑不起来) {
    毛病.push("脚本根本没跑起来：" + 首.跑不起来);
  } else {
    if (首.退出码 !== 例.退出码) {
      毛病.push("退出码应为 " + 例.退出码 + "，实际是 " + 首.退出码);
    }
    if (首.标准输出 !== 例.标准输出) {
      毛病.push("标准输出应为 " + JSON.stringify(例.标准输出) + "，实际是 " + JSON.stringify(首.标准输出));
    }
    if (首.标准错误 !== 例.标准错误) {
      毛病.push("标准错误应为 " + JSON.stringify(例.标准错误) + "，实际是 " + JSON.stringify(首.标准错误));
    }
    if (次.跑不起来 || 次.退出码 !== 首.退出码 || 次.标准输出 !== 首.标准输出 || 次.标准错误 !== 首.标准错误) {
      毛病.push("连跑两次结果不一样，第一次 " + JSON.stringify(首) + "，第二次 " + JSON.stringify(次));
    }
  }

  if (毛病.length > 0) {
    失败条数 += 1;
    console.error("第 " + (序号 + 1) + " 条没过：" + 例.名);
    毛病.forEach(function (条) {
      console.error("  - " + 条);
    });
  }
});

if (失败条数 > 0) {
  console.error("一共 " + 用例.length + " 条检查，" + 失败条数 + " 条没过。");
  process.exit(1);
}

console.log("一共 " + 用例.length + " 条检查全部通过。");
