#!/usr/bin/env node
"use strict";

// 反复能跑的检查：直接调用 结露.js，逐字比对真实输出。
// 只用 Node 自带功能，不读键盘，不装别的库。
// 用法：node 检查.js    全部通过退出码为 0，否则为非零并指出哪条没过。

var spawnSync = require("child_process").spawnSync;
var path = require("path");

var 脚本 = path.join(__dirname, "结露.js");

function 跑一遍(参数) {
  var 结果 = spawnSync(process.execPath, [脚本].concat(参数), {
    encoding: "utf8",
    input: "",
  });
  if (结果.error) {
    throw 结果.error;
  }
  return {
    退出码: 结果.status,
    标准输出: 结果.stdout,
    标准错误: 结果.stderr,
  };
}

var 缺湿度话 = "没法结露：缺了湿度\n";
var 别的错话 = "没法结露：请给出气温、湿度和物面温度三个整数，湿度要在零到一百\n";

var 用例 = [
  { 名: "气温20 湿度60 物面12 正好露点", 参数: ["20", "60", "12"], 退出码: 0, 标准输出: "会结露\n", 标准错误: "" },
  { 名: "气温20 湿度60 物面13 高于露点", 参数: ["20", "60", "13"], 退出码: 0, 标准输出: "不会结露\n", 标准错误: "" },
  { 名: "物面21 高于气温 先倒挂再不结露", 参数: ["20", "60", "21"], 退出码: 0, 标准输出: "温度倒挂\n不会结露\n", 标准错误: "" },
  { 名: "零下 气温-5 湿度80 物面-9", 参数: ["-5", "80", "-9"], 退出码: 0, 标准输出: "会结露\n", 标准错误: "" },
  { 名: "零下 气温-5 湿度80 物面-8", 参数: ["-5", "80", "-8"], 退出码: 0, 标准输出: "不会结露\n", 标准错误: "" },
  { 名: "湿度100 物面等于气温 不算倒挂", 参数: ["20", "100", "20"], 退出码: 0, 标准输出: "会结露\n", 标准错误: "" },
  { 名: "只给两段 第二段是数字也算缺湿度", 参数: ["20", "60"], 退出码: 2, 标准输出: "", 标准错误: 缺湿度话 },
  { 名: "三段里第二段写成缺", 参数: ["20", "缺", "12"], 退出码: 2, 标准输出: "", 标准错误: 缺湿度话 },
  { 名: "一段都没有", 参数: [], 退出码: 2, 标准输出: "", 标准错误: 别的错话 },
  { 名: "湿度101 超界", 参数: ["20", "101", "12"], 退出码: 2, 标准输出: "", 标准错误: 别的错话 },
  { 名: "带小数", 参数: ["20.5", "60", "12"], 退出码: 2, 标准输出: "", 标准错误: 别的错话 },
  { 名: "带正号", 参数: ["+20", "60", "12"], 退出码: 2, 标准输出: "", 标准错误: 别的错话 },
  { 名: "给了四段", 参数: ["20", "60", "12", "7"], 退出码: 2, 标准输出: "", 标准错误: 别的错话 },
];

var 失败 = [];

function 比对(名, 期望, 实际, 哪一项) {
  if (期望 !== 实际) {
    失败.push(
      "没过：" + 名 + " 的" + 哪一项 + "对不上\n" +
      "  期望：" + JSON.stringify(期望) + "\n" +
      "  实际：" + JSON.stringify(实际)
    );
  }
}

用例.forEach(function (例) {
  var 实际 = 跑一遍(例.参数);
  比对(例.名, 例.退出码, 实际.退出码, "退出码");
  比对(例.名, 例.标准输出, 实际.标准输出, "标准输出");
  比对(例.名, 例.标准错误, 实际.标准错误, "标准错误");
});

// 同一组连跑两次，打出来的字必须一样。
var 复跑参数 = ["20", "60", "12"];
var 第一次 = 跑一遍(复跑参数);
var 第二次 = 跑一遍(复跑参数);
["退出码", "标准输出", "标准错误"].forEach(function (项) {
  if (第一次[项] !== 第二次[项]) {
    失败.push(
      "没过：同一组参数连跑两次的" + 项 + "不一样\n" +
      "  第一次：" + JSON.stringify(第一次[项]) + "\n" +
      "  第二次：" + JSON.stringify(第二次[项])
    );
  }
});

if (失败.length > 0) {
  process.stderr.write("检查没全过，共 " + 失败.length + " 处：\n" + 失败.join("\n") + "\n");
  process.exit(1);
}

process.stdout.write("全部 " + 用例.length + " 条用例加一次复跑比对都通过了。\n");
process.exit(0);
